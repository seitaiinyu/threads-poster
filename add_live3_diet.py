def main():
    p=os.path.join(DIR,"content_bank.json")
    bank=json.load(open(p,encoding="utf-8"))
    ex={t["segments"][0].split("\n")[0].strip() for t in bank}
    n=0
    for cat,segs in T:
        if segs[0].split("\n")[0].strip() in ex: continue
