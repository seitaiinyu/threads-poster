def main():
    p=os.path.join(DIR,"content_bank.json")
    bank=json.load(open(p,encoding="utf-8"))
    ex={t["segments"][0].split("\n")[0].strip() for t in bank}
    n=0
    for cat,segs in T:
        if segs[0].split("\n")[0].strip() in ex: continue
        # "cta"キーを付けると回復期(cta_every=0)でも③まとめが削られず3段で配信される
        bank.append({"type":"live","cat":cat,"cta":"","segments":list(segs)}); n+=1
    # 既存のlive投稿にも同じ修正(まとめ段の欠落防止)
    k=0
    for t in bank:
        if t.get("type")=="live" and "cta" not in t:
            t["cta"]=""; k+=1
    json.dump(bank,open(p,"w"),ensure_ascii=False,indent=1)
    print(f"8/15 LIVE由来 {n}本追加 / 既存live {k}本の3段配信を修正 / バンク計 {len(bank)}")

if __name__=="__main__": main()
